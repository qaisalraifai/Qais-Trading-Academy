-- ============================================================================
-- إلغاء ميزة الشهادات — حذف جدول batch_certificates
-- ============================================================================
--
-- قرار صاحب المشروع (٢٠٢٦-٠٨-٢٥): «بدي ألغي فكرتها بالكامل».
--
-- الكود انشال بالكامل بنفس الكوميت:
--   · `lib/certificates.js`
--   · `app/certificate/[code]/` (صفحة التحقّق العامة)
--   · `app/api/certificates/verify/[code]/`
--   · `app/api/batches/certificates/`
--   · `app/api/admin/batches/[id]/certificates/` (إصدار وسحب)
--   · `app/(shell)/course/[id]/CertificatePanel.js`  ← كان **ميتاً** أصلاً
--   · تبويب «الشهادات» بلوحة الدفعات، وقسمها بقائمة الدفعات
--   · شارة «شهادة معتمدة» بصفحة الدورات + مفاتيح الترجمة
--
-- ----------------------------------------------------------------------------
-- 🔴 **اقرأ قبل التشغيل — الحذف نهائي.**
--
-- لو صدرت شهادات لطلاب، عندهم روابط تحقّق (`/certificate/<code>`). الصفحة
-- انحذفت أصلاً فالروابط **مكسورة من لحظة النشر** بغضّ النظر عن هالملف.
-- بس البيانات بتضل موجودة لحد ما تشغّله.
--
-- شوف شو في أول:
--
--   select count(*) as المجموع,
--          min(issued_at) as أقدم,
--          max(issued_at) as أحدث
--   from public.batch_certificates;
--
--   -- ولو بدك تحتفظ بسجلّ قبل الحذف:
--   select * from public.batch_certificates order by issued_at;
--
-- ⚠️ لو العدد **صفر**: نفّذ بلا تردّد.
-- ⚠️ لو أكتر من صفر: القرار إلك — الحذف بيمسح سجلّ مين تخرّج ومتى، ولو
--    رجعت الميزة يوماً ما في طريقة تستعيده.
--
-- ----------------------------------------------------------------------------
-- ⚠️ `restrict` مقصودة مش `cascade`: لو في جدول تاني بيشير عليه ما انتبهنا
--    إله، بدنا الأمر **يفشل** ويورجيه بدل ما يجرف معه أشياء تانية بصمت.
--    (مفحوص بالكود: `batch_certificates` كان مستعملاً بخمس ملفات وكلها
--     انحذفت. الفحص الحقيقي لاعتمادات قاعدة البيانات هو نجاح `restrict`.)
-- ============================================================================

drop table if exists public.batch_certificates restrict;

