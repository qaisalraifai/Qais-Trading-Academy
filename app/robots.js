import { SITE_URL } from "./layout";
import { SESSION_PATHS, SUBSCRIPTION_PATHS } from "@/lib/route-access";

/* ============================================================================
   robots.txt — ما كان موجوداً أصلاً
   ----------------------------------------------------------------------------
   بلاه، الزاحف بيجرّب كل مسار بيلاقيه: صفحات الأعضاء بترجّع تحويلاً لصفحة
   الدخول، ونداءات `/api/*` بترجّع JSON أو 401. ولا وحدة منهن بتنفع كنتيجة
   بحث، وكلهن بتاكل من ميزانية الزحف.

   ⚠️ **القوائم مستوردة مش مكتوبة بالإيد.** `lib/route-access.js` هو مصدر
   سياسة الوصول، فأي مسار محمي جديد بينمنع من الفهرسة **تلقائياً** — بلا
   هيك بتنفتح فجوة صامتة كل ما تنضاف صفحة.

   ⚠️ وهاد **مش** طبقة أمان: `robots.txt` طلب أدب بيحترمه جوجل وبينج، وما
   بيمنع ولا وصول. الفرض الحقيقي بالـmiddleware وبالصفحات نفسها.
   ============================================================================ */
export default function robots() {
  /* `/admin` جوّا `SESSION_PATHS` أصلاً، فبتيجي من هناك. */
  const priv = [...SESSION_PATHS, ...SUBSCRIPTION_PATHS]
    .map((p) => `${p}/`)
    .sort();

  return {
    rules: [
      {
        userAgent: "*",
        allow: "/",
        disallow: [
          "/api/",
          /* معرض المكوّنات — صفحة مراجعة داخلية، وهي `noindex` بصفحتها
             كمان. الاتنان مقصودان: هاد بيمنع الزحف، وذاك بيمنع الظهور لو
             وصلها من رابط خارجي. */
          "/design-system/",
          /* رابط الإحالة — تحويل بحت، ما إله محتوى. */
          "/r/",
          "/auth/",
          ...priv,
        ],
      },
    ],
    sitemap: `${SITE_URL}/sitemap.xml`,
    host: SITE_URL,
  };
}
