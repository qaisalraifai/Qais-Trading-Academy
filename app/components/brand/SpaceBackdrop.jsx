"use client";

import { usePathname } from "next/navigation";
import Starfield from "./Starfield";

/* ============================================================================
   SpaceBackdrop — طبقة الفضاء الواحدة خلف المنصّة كلها.
   ----------------------------------------------------------------------------
   🔴 **الفضاء كان بيوقف عند الصفحة الأولى.** قياس قبل الشغل: `Starfield`
   و`OrbitDiagram` مستعملات بملف **واحد** — `app/page.js`. تسجيل الدخول
   والاشتراك واختيار الدفعة وكل صفحات ما بعد الدخول: صفر. اللون بيكمل
   (`bg-space-1` على الجسم) بس بلا عمق ولا حركة.
   بلاغه: «من الصفحة الأولى لما ندخل روابط المنصّة لآخر صفحة بعد تسجيل الدخول
   وكله مستوحى من الفضاء».

   **نسخة وحدة مركّبة بالجذر** — مش وحدة لكل صفحة. السبب: `RootLayout` ما
   بينهدم بالتنقّل بين الصفحات، فالنجوم بتضل **نفسها** وهي عابرة من صفحة
   لصفحة بدل ما تتولد من جديد كل مرة. وهاد بذاته نص الإحساس المطلوب.

   ⚠️ **بتنطفي على الأدوات الثقيلة** (قراره ٢٠٢٦-٠٨-٣١: «كل المنصّة ما عدا
   الأدوات الثقيلة»). الـReplay والرادار ومحرك QAIS شارتات كانفس بترسم كل
   إطار؛ كانفس تاني وراهن بياكل من الأداء بالضبط وقت ما المطلوب تركيز.

   ⚠️ **وبتنطفي على الصفحة الرئيسية** — إلها معالجتها الخاصة بحقلي نجوم
   داخل قسمين (البطل والدعوة الأخيرة)، فطبقة عامة فوقهن بترسم نجوماً مرتين.
   ============================================================================ */

/* بادئات المسارات اللي ما بتاخد الطبقة. المطابقة على حدود المقاطع —
   `startsWith` خام بيمسك `/replayيات` كمان. */
const EXCLUDED = ["/replay", "/trading-radar", "/market-intelligence"];

export default function SpaceBackdrop() {
  const pathname = usePathname() || "/";

  if (pathname === "/") return null;
  if (EXCLUDED.some((p) => pathname === p || pathname.startsWith(`${p}/`))) return null;

  return (
    <div aria-hidden className="pointer-events-none fixed inset-0 -z-10 overflow-hidden">
      {/* ═══════════ سديم خفيف ═══════════
          تدرّجان قطريان **ثابتان** بيكسروا استواء الخلفية ويعطوا إحساس إنّ
          في «مكان» ورا النجوم.
          ⚠️ الشفافية واطية عمداً (0.16 · 0.09): جُرّبت نسخة سديم قوية
          ومتحرّكة بدل النجوم وانرفضت — «كثير مزعج وألوان قوية وفاقد إحساس
          الفضاء». فدوره هون **خلفية للنجوم** مش بديل عنهن. */}
      <div
        className="absolute inset-0"
        style={{
          background:
            "radial-gradient(1100px 620px at 82% -8%, rgba(124,77,255,0.16), transparent 62%)," +
            "radial-gradient(900px 560px at 8% 106%, rgba(34,211,238,0.09), transparent 60%)",
        }}
      />
      {/* ═══════════ النجوم ═══════════
          كثافة أوطى من الصفحة الرئيسية (0.55 مقابل 1.1): هون خلفية عمل
          بتضل قدّام المستخدم ساعات، مش واجهة بتنشاف مرة.
          ⚠️ `parallax={false}` — الطبقة `fixed`، فالتمرير ما بيحرّكها أصلاً،
          ومستمع التمرير بيصير كلفة بلا أثر. */}
      <Starfield density={0.55} parallax={false} meteors />
      {/* تعتيم للحواف حتى تضل قراءة النص هي الأوضح بالوسط */}
      <div
        className="absolute inset-0"
        style={{
          background:
            "radial-gradient(120% 90% at 50% 45%, transparent 38%, rgba(5,3,8,0.55) 100%)",
        }}
      />
    </div>
  );
}
