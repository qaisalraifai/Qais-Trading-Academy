-- المرحلة 2 من إعادة تصميم نظام الدفعات: التسجيل يصير بمستوى الدفعة
-- (الطالب ينضم للدفعة مرة وحدة، وتلقائيًا بتنفتحله كل دوراتها) بدل ما
-- يختار دفعة لكل دورة لحالها.
--
-- آمنة وإضافية: ما بتحذف ولا صف من تسجيلات طلابك الحاليين، وكل التسجيلات
-- القديمة (لكل دورة لحالها) بتضل تشتغل بالضبط متل ما هي بدون ما يحس فيها
-- أي طالب أو ينخسر تقدمه.

-- عمود course_id صار اختياري (مش إجباري) لأنه التسجيلات الجديدة بمستوى
-- الدفعة مش بمستوى الدورة. التسجيلات القديمة بتضل محتفظة بقيمته زي ما هي.
alter table batch_enrollments alter column course_id drop not null;

-- يمنع الطالب من الانضمام لنفس الدفعة مرتين (بغض النظر عن الدورة)
create unique index if not exists batch_enrollments_user_batch_idx
  on batch_enrollments (user_id, batch_id);
