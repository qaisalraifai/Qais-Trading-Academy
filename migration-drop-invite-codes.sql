-- ⚠️ **الجدول فيه ٣ صفوف** وقت الفحص — أكواد دعوة من التدفّق القديم. ما
--    بيقراها ولا يكتبها أي شي بالمنصّة، بس **الحذف نهائي وما بينرجع**.
--    لو بدك تشوفها قبل، شغّل هالسطر لحاله أول:
--
--        select * from public.invite_codes;
--
-- ----------------------------------------------------------------------------
-- ⚠️ `restrict` مقصودة مش `cascade`: لو طلع في أي اعتماد ما انكشف بالفحص،
