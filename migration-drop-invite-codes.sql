--
-- ----------------------------------------------------------------------------
-- التحقّق قبل الحذف — الجدول غير مستخدم بالكامل:
--
--   الكود        صفر مرجع (بحث مفهرس على كل الريبو: js · jsx · ts · tsx ·
--                json · md · yml · mjs · cjs)
--   ملفات SQL    صفر مرجع بالـ٢٧ ملف هجرة بالريبو
--   Server Actions  ما في ولا واحد بالمشروع أصلاً
--   قاعدة البيانات  صفر functions · صفر triggers · صفر policies · صفر views ·
--                صفر مفاتيح أجنبية  (مفحوصة على pg_proc · pg_trigger ·
--                pg_policy · pg_class · pg_constraint — ٢٠٢٦-٠٨-٢٤)
