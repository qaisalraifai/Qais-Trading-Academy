-- ═══════════════════════════════════════════════════════════════════════════
-- عمود الجنس بجدول profiles — عشان المنصّة تخاطب المستخدم بصيغته
-- ---------------------------------------------------------------------------
-- طلبه: «سؤال الجنس عند التسجيل عشان النظام يخاطبك صح»، وقراره: **إلزامي**.
--
-- ⚠️ **إلزامي عند التسجيل ≠ `NOT NULL` هون.** الحسابات القائمة ما عندها قيمة،
--    فـ`NOT NULL` بترفض الترحيل من أساسه. الإلزام بينفرض بمكانين:
--      · صفحة التسجيل (تجربة المستخدم)
--      · `/api/create-profile` (**البوابة الحقيقية** — فحص العميل بينتخطّى
--        بطلب مباشر، فالخادم هو اللي بيرفض)
--    والعمود بيقبل `NULL` للحسابات القديمة، وبتنعامل بالصيغة الحالية (مذكّر)
--    لحد ما تحدّدها من الإعدادات.
--
-- ⚠️ والقيد `CHECK` مقصود: بلاه أي قيمة نصية بتنقبل، وأول خطأ مطبعي بمسار
--    جديد بيخزّن قيمة ما بتقابلها ولا صيغة — والواجهة بتقع على المذكّر بصمت
--    بدل ما تنكسر، فالعطل بيضل مخفي.
--
-- آمن للتشغيل أكتر من مرة (`IF NOT EXISTS`).
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS gender text;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'profiles_gender_check'
  ) THEN
    ALTER TABLE public.profiles
      ADD CONSTRAINT profiles_gender_check
      CHECK (gender IS NULL OR gender IN ('male', 'female'));
  END IF;
END $$;

COMMENT ON COLUMN public.profiles.gender IS
  'صيغة مخاطبة المستخدم: male | female | NULL (حساب قديم — بيقع على المذكّر).';
