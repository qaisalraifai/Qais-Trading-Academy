/**
 * بيبني سلسلة بطول السلسلة الأساسية بالضبط، كل عنصر بلحظة نظيره.
 *
 * @param {Array<{time:number}>} compareCandles شموع الرمز المترابط
 * @param {Array<{time:number}>} mainCandles    شموع الشارت الأساسي (المحور)
 * @param {(c:object)=>object} toPoint          تحويل الشمعة لنقطة رسم
 * @returns {Array<object>} نقاط بطول `mainCandles`؛ الناقص بيصير `{ time }`
 *
 * ⚠️ `{ time }` بلا قيمة هي **whitespace** بلغة lightweight-charts — بتحجز
 * الموضع بلا ما ترسم، وهيك الفهرس بيضل محاذياً.
 */
export function alignToMainAxis(compareCandles, mainCandles, toPoint) {
  if (!mainCandles?.length) return (compareCandles || []).map(toPoint);

  const byTime = new Map((compareCandles || []).map((c) => [c.time, c]));
  return mainCandles.map((m) => {
    const c = byTime.get(m.time);
    return c ? toPoint(c) : { time: m.time };
  });
}
