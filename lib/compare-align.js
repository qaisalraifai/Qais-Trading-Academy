/* ============================================================================
   lib/compare-align.js — محاذاة سلسلة المقارنة على محور أوقات السلسلة
   الأساسية. وحدة **نقيّة** بلا أي تبعية.

   ---------------------------------------------------------------------------
   🔴 المشكلة اللي بتحلّها (بلاغ مستخدم ٢٠٢٦-٠٨-٢٥):

   لوحتا الشارت متزامنتان **بفهرس الشمعة** (`setVisibleLogicalRange`) — وهاد
   الأسلوب اللي بتوصي فيه lightweight-charts، وبيحاذي عمود N بعمود N بالبكسل.

   ⚠️ بس بيفترض إنّ الفهرس N يعني **نفس اللحظة** باللوحتين. وهاد مش مضمون
   إطلاقاً: الرمزان بيجوا من مزوّدين مختلفين بأعماق مختلفة. مقيس على الإنتاج:

       ناسداك (مع duk)   4551 شمعة · تبلّش 2023-10-19
       SPX    (بلا duk)  2973 شمعة · تبلّش 2024-08-30

   الاتنين بينتهوا بنفس اللحظة، بس المقارنة أقصر بـ**١٥٧٨ شمعة**. فلما
   الأساسي يعرض الفهارس ٣٠٠٠→٤٥٥٠، المقارنة ما عندها شي هناك → **فراغ على
   اليمين**.

   ⚠️ وتمرير `duk` للمقارنة **ما بيحلّها**: SPX مع duk بيعطي ٩١١٣ شمعة —
   الخلل بينقلب للاتجاه التاني. أي مزوّدَين بيعطوا أعماقاً مختلفة، فالمساواة
   بالعدد ما بتنضبط بالمصدر.

   الحل: المحاذاة بحكم **البناء** مش بحكم الصدفة — لكل شمعة بالأساسي، شمعة
   المقارنة بنفس اللحظة، وإلا فراغ.
   ============================================================================ */

/* ═══════════════════════════════════════════════════════════════════════════
   🔴 **المطابقة بالتساوي التام كانت غلط — وكسرت الفريم اليومي.**
   ---------------------------------------------------------------------------
   أول نسخة استعملت `byTime.get(m.time)` — تساوي حرفي. اشتغلت على ٤ ساعات
   وانكسرت على اليومي: **شمعة وحدة بس ظهرت** بلوحة المقارنة.

   السبب موثَّق بالمشروع أصلاً: «الشموع اليومية بتفتح ٢٢:٠٠/٢٣:٠٠/٠٤:٠٠ حسب
   الأداة والمزوّد». والشارت الأساسي بيجي من Dukascopy والمقارنة من يوهو —
   مزوّدان، ساعتا فتح مختلفتان، فما بيتطابق ولا طابع وقت.

   الحل: مطابقة **الأقرب ضمن تسامح** = نص المسافة المعتادة بين شمعتين
   بالسلسلة الأساسية. الوسيط مش المتوسط، عشان الفجوات (عطل نهاية الأسبوع)
   ما تنفخ التسامح.
   ═══════════════════════════════════════════════════════════════════════════ */

const median = (arr) => {
  const s = [...arr].sort((a, b) => a - b);
  return s[s.length >> 1];
};

/** المسافة **الوسيطة** بين شمعتين — الوسيط مش المتوسط عشان عُطل نهاية
    الأسبوع ما تنفخ القيمة. */
function barInterval(candles) {
  const gaps = [];
  for (let i = 1; i < candles.length; i++) {
    const g = candles[i].time - candles[i - 1].time;
    if (g > 0) gaps.push(g);
  }
  return gaps.length ? median(gaps) : 0;
}

/** طور الجلسة: بأي لحظة من الفترة بتفتح شموع هالسلسلة. */
function sessionPhase(candles, interval) {
  if (!interval) return 0;
  return median(candles.map((c) => ((c.time % interval) + interval) % interval));
}

/** رقم الشمعة بسلسلتها، مستقلاً عن ساعة فتح المزوّد. */
const bucketOf = (time, interval, phase) => Math.round((time - phase) / interval);

/**
 * بيبني سلسلة بطول السلسلة الأساسية بالضبط، كل عنصر بلحظة نظيره.
 *
 * @param {Array<{time:number}>} compareCandles شموع الرمز المترابط
 * @param {Array<{time:number}>} mainCandles    شموع الشارت الأساسي (المحور)
 * @param {(c:object)=>object} toPoint          تحويل الشمعة لنقطة رسم
 * @returns {Array<object>} نقاط بطول `mainCandles`؛ الناقص بيصير `{ time }`
 *
 * ⚠️ `{ time }` بلا قيمة هي **whitespace** بلغة lightweight-charts — بتحجز
 * الموضع بلا ما ترسم، وهيك الفهرس بيضل محاذياً.
 */
export function alignToMainAxis(compareCandles, mainCandles, toPoint) {
  const main = mainCandles || [];
  const cmp = compareCandles || [];
  if (!main.length) return cmp.map(toPoint);
  if (!cmp.length) return main.map((m) => ({ time: m.time }));

  /* المطابقة **برقم الشمعة** بعد إزالة طور الجلسة — مش بالقرب الزمني.
     ---------------------------------------------------------------------
     ⚠️ القرب الزمني بيسيء التوزيع مع إزاحة منهجية: بإزاحة ١٦ ساعة على اليومي،
     أقرب شمعة لـ«اليوم د» هي شمعة «اليوم د−١» (٨ ساعات) مش شمعة نفس اليوم
     (١٦ ساعة) — فبينربط كل عمود باليوم الغلط، وأول عمود بيضيع.

     برقم الشمعة: اليوم د بالسلسلتين بياخد نفس الرقم مهما كانت ساعة الفتح. */
  const interval = barInterval(main) || barInterval(cmp);
  if (!interval) {
    const byTime = new Map(cmp.map((c) => [c.time, c]));
    return main.map((m) => (byTime.has(m.time) ? toPoint(byTime.get(m.time)) : { time: m.time }));
  }

  const mainPhase = sessionPhase(main, interval);
  const cmpPhase = sessionPhase(cmp, interval);

  const byBucket = new Map();
  for (const c of cmp) {
    const b = bucketOf(c.time, interval, cmpPhase);
    if (!byBucket.has(b)) byBucket.set(b, c); // أول وحدة بالرقم — بلا تكرار
  }

  return main.map((m) => {
    const c = byBucket.get(bucketOf(m.time, interval, mainPhase));
    return c ? toPoint(c) : { time: m.time };
  });
}
