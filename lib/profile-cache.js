import { cache as reactCache } from "react";
import { createClient } from "@/lib/supabase-server";

/* ============================================================================
   lib/profile-cache.js — صف `profiles` بينتجاب **مرة وحدة لكل طلب**.

   ---------------------------------------------------------------------------
   ⚠️ المشكلة المقيسة: فتحة `/dashboard` كانت تستعلم `profiles` **٣ مرات لنفس
   الصف** (خط الأساس ٢٠٢٦-٠٨-٢٤، بناء إنتاج):

       ١) الـ`middleware`               — فحص الاشتراك
       ٢) `app/(shell)/layout.js`       — `getShellProfile`
       ٣) الصفحة نفسها                  — أعمدتها الخاصة

   والدليل من نفس القياس: `/settings` (بلا فحص اشتراك) = ١ · `/trading-radar`
   (بلا استعلام بالصفحة) = ٢ · `/dashboard` = ٣.

   هالوحدة بتلغي التكرار بين **٢ و٣** — الاتنين بينفّذوا بنفس دورة رسم React
   فبـ`cache` بينوحّدوا. أما استعلام الـ`middleware` فبسياق منفصل تماماً
   (Edge, قبل الرسم) وما بينوصل من هون؛ توحيده بيتطلّب تمرير بترويسة = **سطح
   ثقة جديد**، وهاد قرار مؤجَّل.

   🔴 **ولا سلوك تخويل تغيّر.** نفس الصف، نفس الجلسة، نفس الأعمدة — بس بدل
   ما ينجاب مرتين بينجاب مرة. ما في تخزين **بين** الطلبات: `cache` نطاقها
   الطلب الواحد وبتنتهي معه. لو استعملنا `unstable_cache` (تخزين ثابت) بيصير
   دور المستخدم واشتراكه **بايتين** لفترة — وهاد بالضبط اللي ممنوع.

   ---------------------------------------------------------------------------
   ⚠️ **الوحدة بتاخد `userId` بس — مش عميل Supabase.**
   `cache` بتفهرس على الوسائط. لو مرّرنا العميل، كل منادي بيبعت كائناً جديداً
   فالمفتاح بيختلف كل مرة و**التوحيد ما بيصير أبداً**. فالوحدة بتبني عميلها
   جوّا (نفس الكوكيز، نفس النتيجة).

   ⚠️ **تراجع آمن**: `cache` موجودة ببناء React الخاص بـNext (RSC) بس مش
   ببناء العميل. لو غابت لأي سبب، بنرجع لدالة بلا توحيد — يعني **سلوك
   اليوم** بالضبط، مش انهيار بكل صفحة.
   ============================================================================ */
const memo = typeof reactCache === "function" ? reactCache : (fn) => fn;

/** اتحاد الأعمدة اللي بتلزم الشِل والصفحات — عمود زيادة أرخص من رحلة زيادة.
    ⚠️ `gender` بينجلب هون بالذات لنفس السبب: المخاطبة بتلزم **بكل صفحة**،
    وجلبها لحالها بيعني رحلة شبكية تانية لنفس الصف. */
export const PROFILE_COLUMNS =
  "username, role, subscription_end, current_streak, longest_streak, backtest_balance, gender";

/**
 * صف `profiles` للمستخدم — مرة وحدة لكل طلب.
 * @param {string|null} userId
 * @returns {Promise<object|null>} الصف، أو `null` لو ما في صف
 */
export const getProfileRow = memo(async function getProfileRow(userId) {
  if (!userId) return null;
  const { data } = await createClient()
    .from("profiles")
    .select(PROFILE_COLUMNS)
    .eq("id", userId)
    .maybeSingle();
  return data ?? null;
});
