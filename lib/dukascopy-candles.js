/* ============================================================================
   lib/dukascopy-candles.js
   جالب شموع Dukascopy — مصدر مجاني بالكامل وبدون مفتاح API، هدفه يحل مشكلة
   "حد العمق التاريخي" اللي عند Yahoo Finance (يوهو ما بتحتفظ بشموع الدقيقة
   لأكتر من ~29 يوم للخلف، و5min/15min لحوالي 58 يوم بس - هاد حد بالبيانات
   نفسها عند يوهو، مش حد بعدد الطلبات، فزيادة الطلبات ما بتحل المشكلة).

   Dukascopy (بنك سويسري) عنده بيانات تاريخية تيك-باي-تيك من أول ~2003-2017
   (حسب الأداة) لليوم، لأكتر من 1000 أداة (فوركس، معادن، كريبتو، مؤشرات،
   أسهم)، عام بالكامل وبدون تسجيل. منستخدم مكتبة "dukascopy-node" مفتوحة
   المصدر (npm) اللي بتتعامل مع تنزيل وفك ملفات .bi5 المضغوطة نيابة عنا
   وترجع شموع OHLC جاهزة.

   الفرق عن Yahoo/Twelve Data: هاي مو نقطة نهاية REST سريعة برد JSON فوري -
   المكتبة بتنزّل ملف لكل ساعة/يوم من أرشيف Dukascopy وتجمّعهم، فأول طلب
   لمدى طويل ممكن ياخد كذا ثانية (مش مشكلة هون لأنها بس لأداة الريبلاي
   التاريخية، مش للايف). ما في حد رسمي على عدد الطلبات، بس لازم استخدام
   معقول (batchSize/pause تحت مضبوطين عشان ما نقصف الأرشيف بسرعة جنونية).

   useCache: false عمداً - السيرفرليس (Vercel) نظام ملفاته للقراءة فقط
   تقريباً بكل مكان إلا /tmp المؤقت، فمنعتمد بس على fetch بالميموري بدون أي
   كتابة على القرص.
   ============================================================================ */

import { getHistoricalRates } from "dukascopy-node";

/* فريمات المشروع (1min|5min|15min|1h|4h|1day) → تسمية Dukascopy (m1|m5|m15|h1|h4|d1) */
const INTERVAL_TO_DUKASCOPY = {
  "1min": "m1",
  "5min": "m5",
  "15min": "m15",
  "1h": "h1",
  "4h": "h4",
  "1day": "d1",
};

const INTERVAL_SECONDS = {
  "1min": 60,
  "5min": 300,
  "15min": 900,
  "1h": 3600,
  "4h": 4 * 3600,
  "1day": 24 * 3600,
};

/**
 * يجيب شموع OHLC تاريخية من Dukascopy - بدون حد عمق زمني عملي (لغاية بداية
 * تغطية الأداة نفسها عند Dukascopy، سنين للخلف عادة).
 * @param {string} instrument - رمز Dukascopy (مثل "xauusd"، "eurusd"، بحروف صغيرة)
 * @param {string} interval - أحد مفاتيح INTERVAL_TO_DUKASCOPY (1min|5min|15min|1h|4h|1day)
 * @param {number} wanted - عدد الشموع المطلوبة تقريباً (يُقص لآخر N شمعة)
 * @param {number|null} anchorTimestamp - نقطة قص/Replay اختيارية (Unix seconds)
 * @param {number} budgetMs - مهلة المُستدعي؛ استكمال العمق بيوقف قبلها
 * @param {{getRates?: Function}} deps - حقن للاختبار وبس (شوف التحذير تحت)
 * @returns {Promise<{candles: Array}|{error: string}>}
 */

/* ⚠️ `deps.getRates` **للاختبار وحده** — ولا مُستدعٍ بالتطبيق بيمرّره.
   سببه محدَّد: مسار النجاح بهالدالة بيحتاج شبكة، فكان **غير قابل للاختبار
   بالكامل**. وهاد بالضبط اللي خلّى `ReferenceError` على كل جلب ناجح
   (`4b61026`) يمرق من بناء نظيف ومن ٣٨٤ اختبار ويوصل للإنتاج كـ500.
   متحقَّق بالطفرة: بلا الحقن، حذف كتلة التحويل **ما بيفشّل ولا اختبار**. */
export async function fetchDukascopyCandles(
  instrument,
  interval = "15min",
  wanted = 1000,
  anchorTimestamp = null,
  budgetMs = 0,
  deps = {}
) {
  const getRates = deps.getRates || getHistoricalRates;
  const startedAt = Date.now();
  const timeframe = INTERVAL_TO_DUKASCOPY[interval];
  if (!timeframe) {
    return { error: `فريم غير مدعوم عند Dukascopy: ${interval}` };
  }
  if (!instrument) {
    return { error: "لا يوجد رمز Dukascopy لهذا الأصل" };
  }

  const secPerBar = INTERVAL_SECONDS[interval] || 900;
  const count = Math.min(Number(wanted) || 1000, 20000);
  const nowMs = Date.now();

  /* حماية حرجة: مكتبة dukascopy-node عندها باغ موثّق (Issue #186 على
     GitHub تبعها) - لما يكون "to" المطلوب قريب جداً من الوقت الحالي فعلياً
     ("الآن")، getHistoricalRates بتدخل تسريب ذاكرة وبتطيح الـ process كامل
     بـ"JavaScript heap out of memory" - وهاد الخطأ **مش قابل للإمساك حتى
     بـtry/catch** (بيطيح الـ Node process نفسه، مش بس الـ promise). هاد
     بالضبط كان سبب الـ502 العام (بدون أي JSON body) يلي كنا نشوفه بالكونسول:
     الفنكشن كانت تنهار قبل ما توصل حتى لسطر catch تحت. أرشيف Dukascopy أصلاً
     بيتأخر بالنشر عن اللحظة الحالية (مش لحظي)، فمافي خسارة بيانات حقيقية
     بفرض هامش أمان هون - بس لازم نضمن إنه "to" ما يوصل أبداً لآخر ساعتين. */
  const NOW_SAFETY_MARGIN_MS = 2 * 60 * 60 * 1000;
  const safeNowMs = nowMs - NOW_SAFETY_MARGIN_MS;

  /* منحسب نافذة تغطي عدد الشموع المطلوب (+ هامش 25%) - لو في anchor منخليها
     تنتهي شوي بعد نقطة القص (زي نفس منطق anchor بيوهو/Twelve Data بالضبط)
     عشان الريبلاي يقدر يفوت لأبعد منها، وإلا منخليها تاريخ اليوم (بهامش
     الأمان فوق، مش "الآن" حرفياً). */
  const bufferSeconds = Math.max(secPerBar * 300, 3 * 24 * 60 * 60);
  const spanMs = Math.ceil(secPerBar * count * 1.25) * 1000;

  let toMs, fromMs;
  if (anchorTimestamp && Number.isFinite(anchorTimestamp)) {
    toMs = Math.min(safeNowMs, (anchorTimestamp + bufferSeconds) * 1000);
    fromMs = anchorTimestamp * 1000 - spanMs;
  } else {
    toMs = safeNowMs;
    fromMs = safeNowMs - spanMs;
  }
  if (fromMs >= toMs) fromMs = toMs - secPerBar * 1000 * 10;

  /* حماية ثانية مهمة: Dukascopy عمرها الفعلي يبلّش من 2003 تقريباً (وبعض
     الأدوات لاحقاً - 2016/2017). بس لما يكون count=20000 (الافتراضي من
     الواجهة) وinterval يومي/ساعة، الحساب فوق (secPerBar*count*1.25) بينتج
     مدى تاريخي بعشرات السنين (يوصل لما قبل 1970!) - يعني الكود كان عم
     يطلب من Dukascopy عشرات/مئات الشهور "الفاضية" يلي مافيها بيانات أصلاً
     (قبل وجود الأداة عند Dukascopy)، والمكتبة كانت تحاول تجيبهم كلهم (بمحاولات
     إعادة retryCount لكل شهر فاشل) لحد ما تضرب مهلة withTimeout فوق بدون ما
     توصل حتى لسنين البيانات الحقيقية - فكانت تفشل بصمت وترجع الكود للاحتياطي
     (Yahoo)، ويوهو لليومي بالفوركس تحديداً محدود بعمد بسنتين بس (شوفي
     isDailyForex بـlib/yahoo-candles.js). هاد بالضبط كان سبب "الفوركس بيجيب
     سنتين بس" رغم إنه duk موجود ومفروض يرجّع سنين أكتر بكثير. الحل: منمنع
     fromMs من النزول قبل بداية تغطية Dukascopy الفعلية، بغض النظر عن count
     المطلوب - هيك الطلب يغطي فقط السنين يلي فيها بيانات حقيقية، وبيخلص
     أسرع بكثير وجوا المهلة المسموحة. */
  const DUKASCOPY_EARLIEST_MS = Date.UTC(2003, 0, 1); // 2003-01-01 UTC

  if (fromMs < DUKASCOPY_EARLIEST_MS) fromMs = DUKASCOPY_EARLIEST_MS;
  if (fromMs >= toMs) fromMs = toMs - secPerBar * 1000 * 10;

  /* ══════════════════════════════════════════════════════════════════════
     🔴 **سقف المدى للطلب الواحد — الفريمات اللحظية.**
     ----------------------------------------------------------------------
     العتبة مقيسة على `usatechidxusd` فريم ٤ ساعات، نافذة نظيفة، تهدئة ١٥
     ثانية بين الجسّات، والصعود بيوقف عند أول فشل حتى ما يحرق النافذة:

         ١٢٠ يوم ✓ 531    ١٨٠ ✓ 790    ٢٤٠ ✓ 1053
         ٣٠٠ يوم ✓ 1306   ٣٦٠ ✓ 1578   ٤٨٠ ✗ 429
         (وبجولة مستقلة: ٢٤٠ ✓ · ٤٠٠ ✗)

     فالعتبة بين ٣٦٠ و٤٠٠ يوم. السقف **٣٠٠** — أكبر مدى نجح بجولتين
     مستقلتين، وفيه هامش لأن الميزانية مشتركة بين الطلبات المتتالية.

     ليش هالسقف ضروري: الفريمات اللحظية بتنبني من ملفات أرشيف **يومية**،
     فكلفة الطلب بعدد الأيام. الجدول بـ`count` المستعملة فعلياً:

         count=1000  ٤ ساعات → ٢٥٨ يوم بمرساة   ✓ تحت السقف
         count=3000  ٤ ساعات → ٦٧٥ يوم بمرساة   ✗ **ضعف العتبة**

     و`count=3000` هي بالضبط اللي بيطلبها تسخين الفريمات الخلفي، واللي
     بينطلق لحظة ما يفتح المستخدم قائمة الفريمات — يعني **قبل** تبديله لـ٤
     ساعات مباشرة. فبيتلقى 429، وبيحرق الميزانية، وبعدين طلبه الحقيقي
     (٢٥٨ يوم، سليم بذاته) بيوصل على نافذة محروقة فبينرفض هو كمان.

     ⚠️ اليومي **مستثنى**: بيتبني من ملفات شهرية فكلفته أقل بمراتب — مقيس
        ١١٧٠ يوم بـ315ms بلا أي تقليص. السقف عليه بيقصّ عمقاً بلا سبب.

     ⚠️ السقف بينطبق على **المدى الكامل** (`toMs − fromMs`) مش على `spanMs`
        وحده — الهامش (`bufferSeconds`) بيضيف ٥٠ يوم على ٤ ساعات، وتجاهله
        بيخلّي الحساب يكذب بالضبط بالحالة المكسورة.
     ══════════════════════════════════════════════════════════════════════ */
  const MAX_SPAN_DAYS_INTRADAY = 300;
  if (interval !== "1day") {
    const maxSpanMs = MAX_SPAN_DAYS_INTRADAY * 24 * 60 * 60 * 1000;
    if (toMs - fromMs > maxSpanMs) fromMs = toMs - maxSpanMs;
  }

  /* ============================================================================
     تقليص المدى عند الرفض — الاتساق أهم من العمق.
     ----------------------------------------------------------------------------
     Dukascopy بترجّع **HTTP 429** (مش انتهاء مهلة — الرفض بيجي خلال ١.٢–١.٦
     ثانية). قياس فعلي على الذهب عبر التطبيق المنشور (٢٠٢٦-٠٨-١٦):

         count=5000 → 429 → تراجع لمزوّد أدنى
         count=3000 → 429 → تراجع لمزوّد أدنى
         count=1500 → dukascopy نجح (0.4s)
         count=900  → dukascopy نجح (0.3s)

     وجرّبنا خنق الإيقاع (batchSize أصغر وتوقّف أطول) — **ما نفع**. الحد
     مربوط بعدد ملفات الأرشيف المطلوبة، مش بسرعة الطلبات. فتهدئة الإيقاع
     ما بتتفاداه، بس بتبطّئ الفشل.

     ليش التقليص هو الحل الصح: قياس اتساق الفريمات على نفس الرمز —
         dukascopy (1500) : ١٠٠.٠٪ من الشموع اليومية بتحتوي شموعها · فرق ٠.٠٠٠٪
         twelvedata (3000): ٦٥.٣٪ · فرق ٠.١٥٨٪
         yahoo GC=F       : ١.٦٪ · فرق ٠.٦٨٦٪
     يعني ١٥٠٠ شمعة من Dukascopy **أصلح تحليلياً** من ٥٠٠٠ من مزوّد
     بيناقض حاله. التحليل متعدد الفريمات بينهار على بيانات متناقضة مهما
     كان عمقها.

     فبدل ما ننزل لمزوّد أضعف أول ما نتلقى رفض، منجرّب نفس المزوّد بمدى
     أقصر. التراجع بيضل موجود لو فشل الكل — بس صار آخر خيار مش أول واحد.
     ============================================================================ */
  const SPAN_RETRIES = [1, 0.5, 0.25];

  /* ═══════════════════════════════════════════════════════════════════════
     🔴 **ذاكرة العامل انشالت — كانت بتقفل الرمز على أضيق مدى للأبد.**
     ---------------------------------------------------------------------
     انبنت (`4b7dc8d`) على فرضية إنّ المحاولات الفاشلة بتاكل الميزانية فما
     يضل وقت للاستكمال. والقياس **أسقط الفرضية**: `elapsed 2393` من `6800`
     متاحة — الوقت ما كان القيد أبداً.

     وبقيت الذاكرة تشتغل، وطلع ضررها بالقياس (٢٠٢٦-٠٨-٢٧):

         spanFactor 0.25 · memoHit true · elapsedBeforeBackfillMs **16**

     ١٦ ملّي ثانية = ما جرّب العامل ١ ولا ٠.٥ إطلاقاً. لأن المرشِّح كان
     `SPAN_RETRIES.filter((f) => f <= memoFactor)` — **بيضيّق وما بيوسّع**.
     فأول ما رمز يهبط لـ٠.٢٥ (ولو بسبب ازدحام عابر) بينقفل عليها ما دامت
     النسخة حيّة، حتى لو صارت الظروف تسمح بأوسع.

     ⚠️ وهاد حجب اختبار فرضية التزاحم بالكامل: الذاكرة كانت تفرض ٠.٢٥ مهما
     عملنا، فشحنة `50a0537` ما كان إلها فرصة تبان.

     فلكل طلب بيرجع يجرّب من العامل ١. الكلفة ~٣ ثواني بالحالة السيئة، وهاي
     ثمن مقبول مقابل إنّ الرمز ما ينقفل على ربع عمقه.
     ═══════════════════════════════════════════════════════════════════════ */
  const attempts = SPAN_RETRIES;

  let raw = null;
  let lastError = null;
  let usedFrom = fromMs; // بداية المدى اللي نجح فعلياً — أساس استكمال العمق تحت

  /* ═══════════════════════════════════════════════════════════════════════
     🔴 **تهدئة بين محاولات التقليص — المحاولات كانت تنطلق ورا بعض فوراً.**
     ---------------------------------------------------------------------
     قياس على الإنتاج (٢٠٢٦-٠٨-٢٧) بوضع القص:

         anchored true · provider "yahoo" · duk null
         providerErrors: { dukascopy: "Request failed with status 429" }

     يعني المحاولات التلاتة كلها انرفضت، فنزل ليوهو `NQ=F` اللي تاريخه
     اليومي بيبلّش ٢٠١٨ بدل ٢٠١٤ — وهاي خسارة تلات سنين ونص بالقص.

     وحد Dukascopy مربوط **بعدد ملفات الأرشيف بنافذة زمنية**. المحاولات
     كانت تنطلق بلا أي فاصل، فالتانية والتالتة بيوقعوا جوّا نفس النافذة
     اللي رفضت الأولى — يعني التقليص ما بيساعد أصلاً، بس بيبطّئ الفشل.

     ⚠️ التهدئة **بس لما تكون الميزانية تسمح**: مسار القص عنده ٢٧ ثانية
     ومستعمَل منها ~٥. مسار المباشر عنده ٨ فبتنتخطّى — هناك السرعة أهم،
     والتراجع ليوهو مقبول لأنه بيجيب تاريخاً كافياً للعرض الحي. */
  const RETRY_COOLDOWN_MS = 2500;
  let attemptIndex = 0;

  for (const factor of attempts) {
    if (attemptIndex++ > 0 && budgetMs >= 15000 && Date.now() - startedAt + RETRY_COOLDOWN_MS < budgetMs * 0.7) {
      await new Promise((r) => setTimeout(r, RETRY_COOLDOWN_MS));
    }
    const attemptFrom = factor === 1 ? fromMs : Math.max(DUKASCOPY_EARLIEST_MS, toMs - (toMs - fromMs) * factor);
    try {
      raw = await getRates({
        instrument,
        dates: { from: new Date(attemptFrom), to: new Date(toMs) },
        timeframe,
        priceType: "bid",
        format: "json",
        volumes: true,
        ignoreFlats: true, // بتشيل شموع عطلة الأسبوع "المسطّحة" تلقائياً - نفس مشكلة الشحطة الرفيعة اللي بنعالجها يدوياً بيوهو/Twelve Data
        useCache: false,
        batchSize: 20,
        pauseBetweenBatchesMs: 150,
        retryCount: 2,
        pauseBetweenRetriesMs: 400,
      });
      if (Array.isArray(raw) && raw.length) { usedFrom = attemptFrom; break; }
      lastError = "استجابة فارغة";
      raw = null;
    } catch (e) {
      lastError = e?.validationErrors ? JSON.stringify(e.validationErrors) : e?.message || String(e);
      raw = null;
      /* غير الرفض/الفراغ (رمز غلط، فريم غير مدعوم...) ما بيتحسّن بتقليص
         المدى — منوقف فوراً بدل ما نضيّع وقت الطلب على محاولات ميؤوسة. */
      if (!/429|rate|timeout|ECONNRESET|socket/i.test(String(lastError))) break;
    }
  }

  if (!raw) {
    return { error: `تعذّر جلب بيانات Dukascopy: ${lastError || "سبب غير معروف"}` };
  }

  /* ============================================================================
     🔴 **استكمال العمق لما ينقصّ المدى — التقليص كان بيسلّم ربع البيانات بصمت.**
     ----------------------------------------------------------------------------
     `SPAN_RETRIES` فوق بتقلّص المدى عند الرفض، وهاد صح (الاتساق أهم من العمق).
     بس لما تنجح على `0.25`، بترجع **ربع** المطلوب — و**ما في أي إشارة**:
     `usedFallback: false` و`providerErrors: null`. شكلها سليمة تماماً.

     مقيس على الإنتاج (٢٠٢٦-٠٨-٢٧) عبر `__qtaPaneInfo()`:

         compare  1839 شمعة · أول وقت 2020-09-28 · provider dukascopy
                  usedFallback:false · errors:null

     والحساب بيطابق للحرف: الأقدم `2003-01-01` فالمدى الكامل ٢٣.٦ سنة،
     و`toMs − 23.6×0.25` = **2020-09-28**. يعني الرمز انرفض بالكامل وبالنص
     ونجح بالربع، وما حدا عرف.

     الحل: القطعة اللي نجحت هي **مقاس مثبَت إنه بيمرق عند هالرمز**. فمنكمّل
     الأقدم بقطع **بنفس الحجم** بدل ما نقبل النقص. هاي نفس تقنية التقطيع
     المستعملة أصلاً بالمشروع للفريمات اللحظية (١٦ قطعة ناجحة من ١٨).

     ⚠️ نفس المزوّد ونفس الرمز — فما في خلط جلسات ولا فجوات، وهاد كان شرطه.
     ⚠️ أول قطعة تفشل منوقف ومنرجّع اللي جمعناه. النقص أحسن من طلب فاشل.
     ============================================================================ */
  /* تتبّع تقليص المدى — بيطلع بـ`__qtaChartInfo().loadSource.duk`.
     ⚠️ التقليص **صامت** بطبعه: `usedFallback:false` و`providerErrors:null`
     وهو بيسلّم ربع العمق. بلا هالحقول برجع أخمّن العمق من شكل الشارت. */
  const trace = {
    spanFactor: usedFrom === fromMs ? 1 : Number(((toMs - usedFrom) / (toMs - fromMs)).toFixed(3)),
    budgetMs,
    elapsedMs: Date.now() - startedAt,
  };

  /* ⚠️ **استكمال العمق جوّا الطلب انشال — انقاس فاشلاً خمس مرات.**
     تهدئة ٢٥٠ · ١٤٠٠ · ٢٢٠٠ ملّي · وبميزانية ٢٧ ثانية · وآخرها بالمباشر:
     `chunksTried 1 · chunksOk 0 · stopped 429` بكل مرة. Dukascopy بترفض أي
     طلب أرشيف **تاني بنفس الاستدعاء** مهما انتظرنا.

     ⚠️ وضرره أكبر من ضياع الوقت: الطلب الفاشل **بيحرق نافذة حد الأرشيف**،
     فأول جولة تعميق بعده بترجع 429 كمان. يعني كان بيمنع الحل اللي بيشتغل.
     البديل الشغّال: تعميق بطلبات منفصلة (`ReplayClient.jsx`). */

  const candles = toCandles(raw);
  if (!candles.length) {
    return { error: "بيانات Dukascopy وصلت لكن كلها غير صالحة" };
  }

  return { candles: candles.slice(-count), duk: { ...trace, bars: candles.length } };
}

/* ════════════════════════════════════════════════════════════════════════
   تحويل مخرج المكتبة لشموع المشروع.
   ────────────────────────────────────────────────────────────────────────
   🔴 هالكتلة **انحذفت بالغلط** مع شيل استكمال العمق (`4b61026`): كانت واقعة
   تحته بنفس الدالة، فراحت معه — وضلّ `return` تحت بيشير لـ`candles`.

   النتيجة: `ReferenceError: candles is not defined` على **كل جلب ناجح**،
   يعني 500 على كل طلب Dukascopy شغّال. مقيس على الإنتاج (٢٠٢٦-٠٨-٢٧):
   خمس 500 على `duk=xauusd` و`duk=usatechidxusd`، و`loadSource: null`،
   وانهيار العمق بالقص لأنّ المسار كان بينزل ليوهو المحدود.

   ⚠️ و`npm run build` مرق نظيف و٣٨٤ اختبار نجحوا — لأنّ متغيّر غير معرّف
   جوّا جسم دالة عطل **تشغيل** مش عطل بناء، وهالملف ما كان عليه ولا اختبار.
   عشان هيك انفصلت لدالة مصدَّرة: صار عليها اختبار بيمسك الصنف نفسه.
   ════════════════════════════════════════════════════════════════════════ */
export function toCandles(raw) {
  if (!Array.isArray(raw) || !raw.length) return [];
  return raw
    .map((v) => ({
      time: Math.floor(v.timestamp / 1000),
      open: Number(v.open),
      high: Number(v.high),
      low: Number(v.low),
      close: Number(v.close),
      volume: Number.isFinite(Number(v.volume)) ? Number(v.volume) : 0,
    }))
    .filter(
      (c) =>
        Number.isFinite(c.time) &&
        Number.isFinite(c.open) &&
        Number.isFinite(c.high) &&
        Number.isFinite(c.low) &&
        Number.isFinite(c.close)
    )
    .sort((a, b) => a.time - b.time)
    .filter((c, i, arr) => i === 0 || c.time !== arr[i - 1].time);
}
