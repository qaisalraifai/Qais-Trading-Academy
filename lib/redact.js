/* ═══════════════════════════════════════════════════════════════════════════
   ⚠️ **`detail` بيطلع للعميل — فلازم ينغسل قبل.**
   ---------------------------------------------------------------------------
   التفصيل مفيد للتشخيص (بلاه رجعنا لـ«خطأ غير متوقَّع» بلا أي خيط)، بس رسائل
   الأخطاء بتحمل أحياناً أشياء ما بتنعرض:

     · توكنات JWT كاملة (رسائل مصادقة بتضمّن التوكن أحياناً)
     · مفاتيح خدمة/API بروابط أو ترويسات ظاهرة بنص الخطأ
     · روابط فيها بيانات اعتماد

   الغسل **بالأنماط مش بقائمة حظر**: أي شي بشكل توكن بينستبدل، حتى لو ما
   منعرف من وين إجا. والطول مسقوف عشان ما يطلع جسم رد كامل بالغلط.
   ═══════════════════════════════════════════════════════════════════════════ */
const REDACTIONS = [
  // JWT (ثلاث مقاطع base64url) — بيشمل access/refresh tokens ومفاتيح anon/service
  [/\beyJ[A-Za-z0-9_-]{6,}\.[A-Za-z0-9_-]{6,}\.[A-Za-z0-9_-]*/g, "[توكن محذوف]"],
  // مفاتيح Supabase الجديدة
  [/\bsb_(secret|publishable)_[A-Za-z0-9_-]+/g, "[مفتاح محذوف]"],
  // Bearer/apikey بالترويسات أو النص
  [/\b(bearer|apikey|api[_-]?key|authorization)\s*[:=]\s*\S+/gi, "$1=[محذوف]"],
  // بارامترات حسّاسة بالروابط
  [/\b(access_token|refresh_token|token|key|secret|password)=[^&\s"']+/gi, "$1=[محذوف]"],
  // بيانات اعتماد داخل رابط
  [/\b([a-z][a-z0-9+.-]*):\/\/[^/\s:@]+:[^/\s@]+@/gi, "$1://[اعتماد محذوف]@"],
  // أي سلسلة طويلة بشكل مفتاح
  [/\b[A-Za-z0-9_-]{60,}\b/g, "[سلسلة طويلة محذوفة]"],
];

const MAX_DETAIL = 300;

/** بيشيل التوكنات والمفاتيح من نص خطأ قبل ما يطلع بالرد. */
export function redactSecrets(text) {
  if (typeof text !== "string") return text == null ? "" : String(text);
  let out = text;
  for (const [pattern, replacement] of REDACTIONS) out = out.replace(pattern, replacement);
  return out.length > MAX_DETAIL ? out.slice(0, MAX_DETAIL) + "…" : out;
}
