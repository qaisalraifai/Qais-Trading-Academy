import { headers } from "next/headers";
import { createClient } from "@/lib/supabase-server";

/* ============================================================================
   lib/auth-context.js — هوية المستخدم للصفحات، بلا رحلة شبكية مكرَّرة.

   ---------------------------------------------------------------------------
   ⚠️ المشكلة: كل انتقال صفحة كان يدفع `auth.getUser()` **مرتين** — مرة
   بالـ`proxy` ومرة بالصفحة — لنفس الفحص بالضبط. و`getUser()` مش قراءة
   محلية: هي **رحلة شبكية** لخادم Supabase بتتحقق من التوكن. فبانتقال واحد
   بيصير: proxy (getUser + profiles) ثم الصفحة (getUser + استعلاماتها) —
   والأولى والتالتة نفس الشي حرفياً.

   الـ`proxy` بيمرّر الهوية بترويسة داخلية بعد ما يتحقق منها، وهون
   منقراها.

   ---------------------------------------------------------------------------
   🔴 **الثقة مشروطة بمسحة الـproxy، مش بوجود الترويسة.**

   Next.js بيمرّر ترويسات الطلب الداخلة كما هي، فالترويسة **قابلة للتزوير من
   برّا** بطبيعتها. اللي بيخليها موثوقة إنه الـ`proxy` بيمسحها بلا شرط
   من كل طلب قبل أي فرع، وما بيكتبها إلا من `auth.getUser()` المتحقَّقة.

   عشان هيك:
   · لو غابت → **ما منفترض إنه ما في مستخدم**. منرجع لـ`getUser()` كامل.
     (مسار ما مرّ على الـproxy، أو تغيّر الـmatcher، أو تشغيل محلي غريب.)
   · ولا منقبل منها إلا **المعرّف**. أي بيانات تانية (دور، اشتراك، إيميل)
     بتنجاب من قاعدة البيانات، مش من ترويسة.

   ⚠️ ممنوع استعمال هالوحدة بمسارات `/api` — الـ`proxy` بيرجع مبكراً
   لمسارات API (بعد المسح)، فالترويسة بتكون فاضية دايماً هناك وما في فايدة.
   ============================================================================ */
const AUTH_HEADER = "x-qta-uid";

/**
 * معرّف المستخدم المتحقَّق، أو null.
 * بيرجّع من الترويسة لو موجودة، وإلا بيعمل الفحص الكامل.
 */
export async function getVerifiedUserId() {
  /* ⚠️ `headers()` صارت async من Next 15 — زي `cookies()` بالضبط. */
  const fromHeader = (await headers()).get(AUTH_HEADER);
  if (fromHeader) return fromHeader;

  const supabase = await createClient();
  const { data: { user } } = await supabase.auth.getUser();
  return user?.id ?? null;
}
