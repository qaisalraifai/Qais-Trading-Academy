/** القيم المقبولة — نفس قيد `CHECK` بالترحيل حرفياً. */
export const GENDERS = ["male", "female"];

/* ═══════════════════════════════════════════════════════════════════════════
   الكوكي — **مرآة للعمود مش مصدراً بديلاً**
   ---------------------------------------------------------------------------
   المخاطبة بتلزم بكل صفحة، والجذر (`app/layout.js`) ما بيعمل ولا استعلام
   اليوم. قراءة العمود من هناك بتضيف **رحلة شبكية لـSupabase على كل صفحة
   بالمنصّة** — بما فيها الصفحات العامة اللي ما فيها مستخدم أصلاً.

   فبنعمل نفس اللي بيعمله `qta_locale` بالضبط: العمود بـ`profiles` هو مصدر
   الحقيقة، والكوكي نسخة سريعة بتتكتب لما تتغيّر القيمة. ⚠️ ولو تعارضوا،
   العمود بيغلب — الكوكي بينكتب من جديد عند أول تسجيل دخول.
   ⚠️ ولا معلومة حسّاسة فيه: قيمة من قيمتين معروفتين، وما بينبنى عليه ولا
   قرار صلاحية.
   ═══════════════════════════════════════════════════════════════════════════ */
export const GENDER_COOKIE = "qta_gender";

/** هل القيمة صيغة مخاطبة صالحة؟ (`null`/غياب **مش** صالح — للفرض عند التسجيل) */
export function isValidGender(value) {
  return GENDERS.includes(value);
}

/**
 * بتختار الصيغة المناسبة.
 *
 * @param {string|null|undefined} gender  `"male"` · `"female"` · غياب
 * @param {string} masculine  صيغة المذكّر — **وهي الاحتياطي**
 * @param {string} feminine   صيغة المؤنّث
 * @returns {string}
 *
 * ⚠️ الاحتياطي **المذكّر مش سلسلة فاضية**: أي قيمة غير متوقّعة بترجّع نصّاً
 * سليماً بدل ما تفضّي الواجهة. عطل بالبيانات ما بيصير عطلاً بالعرض.
 */
export function byGender(gender, masculine, feminine) {
  return gender === "female" ? feminine : masculine;
}

/**
 * صيغة جاهزة للقاموس: بتاخد نصّاً فيه بديلان مفصولان بـ`|` وبترجّع الصح.
 * مثال: `"مرحباً بك|مرحباً بكِ"` → حسب الصيغة.
 *
 * ⚠️ نص بلا `|` بيرجع كما هو — فأي مفتاح لسا ما انكتبت إله صيغة مؤنّثة
 * بيشتغل عادي بدل ما يطلع فاضي. هيك بنقدر نعرّب على دفعات بلا ما نكسر شي.
 */
export function pickForm(text, gender) {
  if (typeof text !== "string") return text;
  const i = text.indexOf("|");
  if (i === -1) return text;
  return gender === "female" ? text.slice(i + 1) : text.slice(0, i);
}
