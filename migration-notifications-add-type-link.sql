-- ============================================================================
-- notifications: إضافة العمودين الناقصين `type` و`link`
-- ============================================================================
--
-- 🔴 العَرَض: `/api/notifications?limit=5` بيرجّع **٥٠٠** بكل تحميل للداشبورد.
--
-- السبب: مخطط الإنتاج **ناقص عمودين** عن اللي الكود بيتوقّعه.
-- مقيس على قاعدة الإنتاج (٢٠٢٦-٠٨-٢٥):
--
--   الموجود   id · user_id · title · message · read · created_at
--   المطلوب   … + type · link
--
-- والمسار بيعمل `select id, type, title, message, link, read, created_at`
-- فـPostgREST بترفض الاستعلام.
--
-- ----------------------------------------------------------------------------
-- ⚠️ **الأثر أوسع من رسالة الخطأ.** كل مسارات **الكتابة** بتُدرج العمودين:
--
--   lib/notifications.js                               type · link
--   app/api/admin/quick-add/route.js                   type · link
--   app/api/admin/batches/[id]/announcements/route.js  type · link
--   app/api/admin/users/[id]/action/route.js           title · message
--
-- وفشل الإدراج بينكتب بـ`console.error` وبس — **بلا أي أثر للمستخدم**. يعني
-- ولا إشعار انوصّل: لا عمولة ولا شارة ولا إعلان دفعة ولا بث. الجرس فاضي
-- لأن الكتابة بتفشل، مش لأنه ما في نشاط.
--
-- ----------------------------------------------------------------------------
-- ⚠️ `migration-notifications.sql` كان **صح** — هو مشتقّ من استعمال الكود
--    وفيه العمودان. الانحراف بالإنتاج: الجدول انعمل يدوياً بسوبابيس بلاهن.
--    وبما إنّ ذاك الملف كله `if not exists`، تشغيله ما بيصلّح جدولاً موجوداً
--    ناقص أعمدة — لهيك هالملف منفصل.
--
-- ⚠️ العمودان **nullable وبلا افتراضي** — ما في إعادة كتابة للجدول ولا لمس
--    للصفوف الموجودة. التنفيذ فوري حتى على جدول كبير.
--    والصفوف القديمة بتصير `type = null`، وهاد مقبول: `type` اختياري
--    بالمخطط (`type text` بلا `not null`) والواجهة بتتعامل مع غيابه.
-- ============================================================================

alter table public.notifications add column if not exists type text;
alter table public.notifications add column if not exists link text;

